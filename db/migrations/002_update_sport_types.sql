-- ==============================================================================
-- Миграция 002: Обновление справочника видов спорта
-- Утвержденный набор видов спорта:
-- 1. Футбол
-- 2. Баскетбол
-- 3. Волейбол
-- 4. Универсальная площадка
-- 5. Легкая атлетика
-- ==============================================================================

-- 1. Обновляем наименование универсальных площадок
UPDATE sport_types 
SET name = 'Универсальная площадка', 
    description = 'Многофункциональные спортивные площадки для командных игровых видов спорта'
WHERE name = 'Универсальная' OR id = 4;

-- 2. Перенаправляем существующие площадки со старой легкой атлетики (id 7) на id 5
UPDATE venues SET sport_type_id = 5 WHERE sport_type_id = 7;

-- 3. Удаляем неиспользуемые старые категории (теннис и дублирующую легкую атлетику)
DELETE FROM venues WHERE sport_type_id = 6;
DELETE FROM sport_types WHERE id IN (6, 7);

-- 4. Переименовываем запись id 5 (Воркаут) в «Легкая атлетика»
UPDATE sport_types 
SET name = 'Легкая атлетика', 
    description = 'Легкоатлетические стадионы, беговые дорожки, секторы для прыжков и оборудование для общефизической подготовки'
WHERE id = 5;
